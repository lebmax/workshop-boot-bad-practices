CREATE TABLE IF NOT EXISTS transaction_demo_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name VARCHAR(64) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS transaction_pitfall_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario VARCHAR(64) NOT NULL,
    marker VARCHAR(128) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS lost_update_counter (
    id INTEGER PRIMARY KEY,
    counter_value BIGINT NOT NULL
);

MERGE INTO lost_update_counter (id, counter_value) KEY (id) VALUES (1, 0);
